@runtime_checkable
class IActivityStore(Protocol):
    """Contract for ActivityStore and ActivityStoreLocal.

    Append-only agent-activity ledger: entries are recorded once and never
    updated or deleted, save for the single ``mark_reverted`` marker that
    records that a later entry undid this one. There is deliberately no
    ``update``/``delete`` method — the append-only shape is the point.
    """

    def record(self, entry: dict[str, Any]) -> str: ...
    def list_entries(
        self,
        principal: str | None = ...,
        since: str | None = ...,
        operation: str | None = ...,
        limit: int = ...,
        principal_kind: str | None = ...,
    ) -> list[dict[str, Any]]: ...
    def get_entry(self, entry_id: str) -> dict[str, Any] | None: ...
    def mark_reverted(self, entry_id: str, reverted_by_entry_id: str, ts: str | None = ...) -> None: ...


