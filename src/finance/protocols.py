"""Protocol definitions for the six dual-backend service interfaces.

Using Protocol (structural subtyping) rather than ABC means:
  - Static type checkers (mypy, pyright) verify API compliance without
    requiring explicit inheritance in both backends.
  - Agents can read this single file to understand the full contract for
    every service in the system.

Import example:
    from src.finance.protocols import ITransactionsDB
    def get_transactions_db() -> ITransactionsDB: ...
"""

from collections.abc import Mapping, Sequence
from decimal import Decimal
from typing import Any, Protocol, TypedDict, runtime_checkable


class _TransactionItemCore(TypedDict):
    """The two composite-key attributes present on every transaction row.

    ``ForwardedTo`` (partition) and ``DateFileName`` (sort) are required: both
    backends always write them (DynamoDB item build; SQLite ``NOT NULL`` PK
    columns), and even the narrowest projections — the DynamoDB
    ``scan_by_category`` ``ProjectionExpression`` and ``TRANSACTION_LIST_PROJECTION``
    — carry both. Splitting them into a required core (vs. the ``total=False``
    extension below) legalizes ``item["ForwardedTo"]`` / ``item["DateFileName"]``
    subscripts without a ``reportTypedDictNotRequiredAccess`` error.
    """

    ForwardedTo: str
    DateFileName: str


class TransactionItem(_TransactionItemCore, total=False):
    """A transaction row as stored — PascalCase, DynamoDB-shaped.

    Both backends return this shape (`SQLite` via ``row_to_item``); every key
    below is ``total=False`` because projections and older rows omit them (the
    two always-present key attributes live on ``_TransactionItemCore``). Nested
    audit dicts stay loose (``dict[str, Any]``) at this ratchet stage — do not
    chase nested typing.
    """

    FileName: str
    Date: str
    Amount: Decimal | float | None
    Company: str | None
    Category: str | None
    Institution: str | None
    TransactionType: str | None
    Name: str | None
    UserId: str | None
    FromName: str | None
    FromEmail: str | None
    ToName: str | None
    ToEmail: str | None
    Subject: str | None
    Body: str | None
    TransactionHash: str
    CategoryAudit: dict[str, Any]
    ExtractionAudit: dict[str, Any]
    TransactionContext: dict[str, Any]
    Ignored: bool
    Comment: str | None
    DeletedAt: str | None
    StatementSource: str | None
    CreatedAt: str


